import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const source = new URL('./', import.meta.url);

// Files in `src` that are not schema modules of the root export: separate package entry points,
// scripts, the root export itself and this file's output.
const excluded = new Set([
  'client.ts',
  'generate-index.ts',
  'generate-openapi.ts',
  'generated.ts',
  'index.ts',
  'openapi.ts',
  'staff.ts',
]);

const sourceFiles = async (directory: URL) =>
  (await readdir(directory))
    .filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts'))
    .sort();

/**
 * Renders `generated.ts`: the route record assembled from the package groups in `domains`, and a
 * re-export of every schema module in `src`. Fails when a group file does not export exactly one
 * `<name>Contracts` record. The output is already in Prettier's format.
 */
export async function renderIndex(): Promise<string> {
  const groups = await Promise.all(
    (await sourceFiles(new URL('domains/', source))).map(async (file) => {
      const text = await readFile(new URL(`domains/${file}`, source), 'utf8');
      const names = [...text.matchAll(/^export const (\w+Contracts)\b/gm)];
      const name = names[0]?.[1];
      if (!name || names.length !== 1)
        throw new Error(
          `domains/${file} must export one <name>Contracts record`,
        );

      return { file, name };
    }),
  );
  const modules = (await sourceFiles(source)).filter(
    (file) => !excluded.has(file),
  );

  return [
    '// Generated by src/generate-index.ts. Run `pnpm --filter @luma/api-contract generate:index`',
    '// after adding or removing a schema module in src or a route group in src/domains.',
    "import { systemContract } from './contracts/system.js';",
    ...groups.map(
      ({ file, name }) =>
        `import { ${name} } from './domains/${file.replace(/\.ts$/, '.js')}';`,
    ),
    '',
    '/**',
    " * The route record's type, named so declaration output references each area's contract instead",
    " * of expanding every route schema into one type that exceeds the compiler's serialization limit.",
    ' */',
    'type ApiContract = ' +
      groups
        .map(({ name }, index) => `${index ? '  ' : ''}typeof ${name} &`)
        .join('\n') +
      ' {',
    '    system: typeof systemContract;',
    '  };',
    '',
    '/**',
    ' * Every customer API route, keyed by area. Route keys form OpenAPI operation IDs, such as',
    ' * `orders.list`. Add an area to the group of the package that serves it, in `domains`.',
    ' */',
    'export const apiContract: ApiContract = {',
    ...groups.map(({ name }) => `  ...${name},`),
    '  system: systemContract,',
    '};',
    '',
    ...modules.map(
      (file) => `export * from './${file.replace(/\.ts$/, '.js')}';\n`,
    ),
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  await writeFile(new URL('generated.ts', source), await renderIndex());
