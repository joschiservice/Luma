import { readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../../', import.meta.url);
let entries;
try {
  entries = await readdir(new URL('packages/apps/', root), {
    withFileTypes: true,
  });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  entries = [];
}
const names = entries
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const imports = [];
const dependencies = {};
for (const name of names) {
  const pkg = JSON.parse(
    await readFile(new URL(`packages/apps/${name}/package.json`, root), 'utf8'),
  );
  imports.push(
    `import { createApp as app${imports.length} } from '${pkg.name}';`,
  );
  dependencies[pkg.name] = 'workspace:*';
}
await writeFile(
  new URL('packages/app-catalog/src/generated.ts', root),
  `// Generated by tooling/apps/generate.mjs.\nimport type { AppFactory } from '@luma/app-host';\n${imports.join('\n')}\nexport const factories: readonly AppFactory[] = [${names.map((_, i) => `app${i}`).join(', ')}];\n`,
);
const path = new URL('packages/app-catalog/package.json', root);
const pkg = JSON.parse(await readFile(path, 'utf8'));
for (const name of Object.keys(pkg.dependencies))
  if (name.startsWith('@luma/app-') && name !== '@luma/app-host')
    delete pkg.dependencies[name];
Object.assign(pkg.dependencies, dependencies);
await writeFile(path, JSON.stringify(pkg, null, 2) + '\n');
// Provider fixtures follow the app packages present in this checkout.
for (const file of [
  'package.json',
  'packages/application-runtime/package.json',
]) {
  const path = new URL(file, root);
  const pkg = JSON.parse(await readFile(path, 'utf8'));
  for (const key of Object.keys(pkg.devDependencies))
    if (
      key.startsWith('@luma/app-') &&
      !['@luma/app-host', '@luma/app-catalog'].includes(key)
    )
      delete pkg.devDependencies[key];
  Object.assign(pkg.devDependencies, dependencies);
  await writeFile(path, JSON.stringify(pkg, null, 2) + '\n');
}

// Typechecking and test collection include only suites whose app fixtures are present.
const suites = JSON.parse(
  await readFile(
    new URL('packages/application-runtime/app-test-suites.json', root),
    'utf8',
  ),
);
await writeFile(
  new URL('packages/application-runtime/tsconfig.apps.json', root),
  JSON.stringify(
    {
      exclude: suites
        .filter((suite) => suite.apps.some((app) => !names.includes(app)))
        .flatMap((suite) => suite.files),
    },
    null,
    2,
  ) + '\n',
);
