import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';

import { Pool } from 'pg';
import ts from 'typescript';

import { environment, state } from '../dev/environment.mjs';

const id = process.argv[2];
if (id) {
  if (!/^[a-f0-9]{16}$/.test(id))
    throw new Error('Expected a 16-character luma.db.query_id');
  let found = false;

  async function visit(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts')) {
        const source = ts.createSourceFile(
          path,
          await readFile(path, 'utf8'),
          ts.ScriptTarget.Latest,
          true,
        );

        function inspect(node) {
          if (
            (ts.isStringLiteral(node) ||
              ts.isNoSubstitutionTemplateLiteral(node)) &&
            createHash('sha256')
              .update(node.text)
              .digest('hex')
              .slice(0, 16) === id
          ) {
            console.log(
              `${path}:${source.getLineAndCharacterOfPosition(node.getStart()).line + 1}\n${node.text}`,
            );
            found = true;
          }
          ts.forEachChild(node, inspect);
        }

        inspect(source);
      }
    }
  }

  await visit('apps/api/src');
  if (!found)
    console.log(
      'No static SQL literal matched. The query may be generated by the ORM or assembled dynamically.',
    );
} else {
  const { migrationUrl } = await environment(await state());
  const pool = new Pool({ connectionString: migrationUrl, max: 1 });
  try {
    const { rows } =
      await pool.query(`SELECT calls, round(total_exec_time::numeric, 2) AS total_ms,
      round(mean_exec_time::numeric, 2) AS mean_ms, rows, shared_blks_hit, shared_blks_read,
      query FROM pg_stat_statements WHERE dbid = (SELECT oid FROM pg_database WHERE datname = current_database())
      AND userid IN (SELECT oid FROM pg_roles WHERE rolname IN ('luma_api', 'luma_worker'))
      ORDER BY total_exec_time DESC LIMIT 20`);
    console.table(rows);
  } finally {
    await pool.end();
  }
}
